let db,server,origin,temporary;
test.beforeAll(async()=>{
 temporary=await mkdtemp(resolve('.cache','browser-shop-'));process.env.UPLOAD_DIR=resolve(temporary,'uploads');
 db=openDatabase(':memory:');createOwner(db,{email:'equipe@example.test',password:'Teste-browser-isolado-123'});
 db.prepare("UPDATE shop_content SET payload=json_set(payload,'$.acceptingOrders',json('true'))").run();
 server=createApp({db});server.listen(0,'127.0.0.1');await once(server,'listening');origin=`http://127.0.0.1:${server.address().port}`;
});
test.afterAll(async()=>{await new Promise(resolve=>server.close(resolve));db.close();delete process.env.UPLOAD_DIR;if(temporary){expect(temporary.startsWith(resolve('.cache')+sep)).toBe(true);await rm(temporary,{recursive:true,force:true});}});

